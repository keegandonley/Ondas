#!/bin/sh

set -eu

REPOSITORY_PATH="${CI_PRIMARY_REPOSITORY_PATH:?CI_PRIMARY_REPOSITORY_PATH is not set}"

# Xcode Cloud only supplies custom values as environment variables; unlike command-line build
# settings, those do not override values assigned by an .xcconfig. Materialize the ignored local
# override before project generation so an archive cannot silently inherit the public
# `com.example.ondas` defaults. Configure these three Xcode Cloud environment variables for every
# workflow that signs this app:
#   ONDAS_DEVELOPMENT_TEAM
#   ONDAS_MAIN_APP_BUNDLE_IDENTIFIER
#   ONDAS_MENU_BAR_URL_SCHEME
: "${ONDAS_DEVELOPMENT_TEAM:?ONDAS_DEVELOPMENT_TEAM must be configured in Xcode Cloud}"
: "${ONDAS_MAIN_APP_BUNDLE_IDENTIFIER:?ONDAS_MAIN_APP_BUNDLE_IDENTIFIER must be configured in Xcode Cloud}"
: "${ONDAS_MENU_BAR_URL_SCHEME:?ONDAS_MENU_BAR_URL_SCHEME must be configured in Xcode Cloud}"

validate_setting() {
    value="$1"
    pattern="$2"
    name="$3"
    if ! printf '%s\n' "$value" | grep -Eq "$pattern"; then
        echo "error: $name has an invalid value" >&2
        exit 1
    fi
}

validate_setting "$ONDAS_DEVELOPMENT_TEAM" '^[A-Z0-9]{10}$' ONDAS_DEVELOPMENT_TEAM
validate_setting "$ONDAS_MAIN_APP_BUNDLE_IDENTIFIER" '^[A-Za-z0-9][A-Za-z0-9.-]*$' ONDAS_MAIN_APP_BUNDLE_IDENTIFIER
validate_setting "$ONDAS_MENU_BAR_URL_SCHEME" '^[A-Za-z][A-Za-z0-9+.-]*$' ONDAS_MENU_BAR_URL_SCHEME

umask 077
IDENTITY_OVERRIDE="$REPOSITORY_PATH/Config/Identity.local.xcconfig"
{
    echo "// Generated by ci_post_clone.sh from Xcode Cloud environment settings."
    printf '%s\n' "ONDAS_DEVELOPMENT_TEAM = $ONDAS_DEVELOPMENT_TEAM"
    printf '%s\n' "ONDAS_MAIN_APP_BUNDLE_IDENTIFIER = $ONDAS_MAIN_APP_BUNDLE_IDENTIFIER"
    printf '%s\n' "ONDAS_MENU_BAR_URL_SCHEME = $ONDAS_MENU_BAR_URL_SCHEME"
} > "$IDENTITY_OVERRIDE"

# Xcode Cloud's `brew install xcodegen` is unreliable. Always use the verified,
# pinned release binary rather than an image-provided version that may drift.
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
XCODEGEN_BIN_DIR="$(sh "$SCRIPT_DIR/install_xcodegen.sh" "${TMPDIR:-/tmp}/xcodegen-dist")"
export PATH="$XCODEGEN_BIN_DIR:$PATH"

cd "$REPOSITORY_PATH"
xcodegen generate --spec project.yml
